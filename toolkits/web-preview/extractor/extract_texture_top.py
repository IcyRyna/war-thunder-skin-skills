"""Extract supported DDSx top mips for texture analysis without inventing mip data.

Windows x64; uses the pinned DAE native decompressor. Square 2D BC1/BC2/BC3
and BC7 are supported. Kaiser-generated lower levels are not reconstructed.
"""
from __future__ import annotations
import argparse
import contextlib
import fnmatch
import json
from pathlib import Path
import struct
import sys

from archives import DxpArchive, FormatError
from dae_backend import backend
from mesh_export import filename


def top_mip(data: bytes, meta: dict):
    width,height=meta['width'],meta['height']
    if width!=height:
        raise FormatError('Non-square DDSx dimension order is not validated by this extractor')
    if meta.get('depth',0)>1 or meta['flags'] & (0x800|0x1000|0x200000):
        raise FormatError('Cubemaps, volumes and arrays are not supported')
    if meta['flags'] & 0x20000:
        raise FormatError('Texture needs a paired base texture; standalone decode is not sufficient')
    block_size={'DXT1':8,'DXT3':16,'DXT5':16,'BC7 ':16}.get(meta['fourcc'])
    if block_size is None:
        raise FormatError(f"Unsupported top-mip format {meta['fourcc']!r}")
    size=lambda level: max(1,(max(1,width>>level)+3)//4)*max(1,(max(1,height>>level)+3)//4)*block_size
    top_size=size(0)
    note={}
    if meta['flags'] & 0x4000:
        if len(data)!=top_size+12:
            raise FormatError('Unexpected Kaiser-generated mip payload layout')
        payload=data[:top_size]
        note['generator_tail_floats']=list(struct.unpack('<3f',data[-12:]))
        note['source_lower_mips']='Generated by the runtime; not stored as ordinary DDS mip blocks.'
    else:
        expected=sum(size(level) for level in range(meta['mips']))
        if len(data)!=expected:
            raise FormatError('Decoded payload does not match the declared block mip sizes')
        payload=data[-top_size:] if meta['flags'] & 0x40000 else data[:top_size]
        note['source_lower_mips']='Stored mip chain; only its top level exported for analysis.'
    header=[0]*31
    header[0]=124; header[1]=0x81007; header[2]=height; header[3]=width
    header[4]=top_size; header[6]=1; header[18]=32; header[19]=4; header[26]=0x1000
    extension=b''
    if meta['fourcc']=='BC7 ':
        header[20]=int.from_bytes(b'DX10','little')
        extension=struct.pack('<5I',98,3,0,1,0)
    else:
        header[20]=int.from_bytes(meta['fourcc'].encode('ascii'),'little')
    return b'DDS '+struct.pack('<31I',*header)+extension+payload,note


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('pack',type=Path)
    p.add_argument('--match',action='append',required=True,help='Resource glob; repeat to select more textures')
    p.add_argument('--out',type=Path,required=True)
    args=p.parse_args()
    try:
        output=args.out.resolve(); source=args.pack.resolve()
        if output==source.parent or source.parent in output.parents:
            raise FormatError('Output must be outside the source package directory')
        output.mkdir(parents=True,exist_ok=True)
        archive=DxpArchive(source)
        records=[]
        with (output/'decode.log').open('w',encoding='utf-8') as log,contextlib.redirect_stdout(log):
            runtime=backend()
            for entry in archive.entries:
                if not entry.size or not any(fnmatch.fnmatchcase(entry.name,pat) for pat in args.match):
                    continue
                meta=entry.extra
                if meta['uncompressed_bytes']>512*1024*1024:
                    raise FormatError('Native decompression output exceeds 512 MiB')
                hdr=runtime.material.DDSx.Header(runtime.material.BinFile(bytes.fromhex(meta['header_hex'])))
                tex=runtime.material.DDSx(str(source),entry.name,hdr.memSz,entry.offset,hdr)
                data=tex.getData()
                if len(data)!=meta['uncompressed_bytes']:
                    raise FormatError('Native decompressed size differs from DDSx metadata')
                dds,note=top_mip(data,meta)
                name=filename(entry.name.rstrip('*').split('*')[0])+'_top.dds'
                target=output/name
                if target.exists():
                    raise FormatError(f'Output already exists: {target}')
                target.write_bytes(dds)
                records.append({'source_pack':str(source),'resource':entry.name,'file':str(target),
                                'metadata':meta,**note,'exported_mips':1})
        if not records:
            raise FormatError('No stored texture payload matched the requested resources')
        (output/'manifest.json').write_text(json.dumps(records,ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps({'output':str(output),'textures':len(records),'exported_mips':1},indent=2))
        return 0
    except (OSError,ValueError) as exc:
        print(f'Top-mip extraction failed: {exc}',file=sys.stderr)
        return 1


if __name__=='__main__':
    raise SystemExit(main())
